# Iterating through a manually created list
# 'i' will take each value from the list one by one
num = [1, 2, 3, 4, 5]
for i in num:
    print(i)


# Using range to generate numbers automatically
# Syntax: range(start, stop) -> stop is not included
# This loop will run from 1 to 1000
for i in range(1, 1001):
    print(i)